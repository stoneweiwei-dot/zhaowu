const NAKSHATRA_WIDTH = 360 / 27;

const mod = (n: number, m: number) => ((n % m) + m) % m;
const normal = (n: number) => mod(n, 360);
const signOf = (n: number): ZodiacSign => Math.floor(normal(n) / 30) as ZodiacSign;
const houseOf = (point: ZodiacSign, lagna: ZodiacSign) => mod(point - lagna, 12) + 1;
const iso = (ms: number) => new Date(ms).toISOString();
const month = (ms: number) => iso(ms).slice(0, 7);
const finite = (n: unknown): n is number => typeof n === 'number' && Number.isFinite(n);

export function nakshatraOf(longitude: number): NakshatraPosition {
  if (!finite(longitude)) throw new Error('Invalid nakshatra longitude');
  const lon = normal(longitude);
  const index = Math.floor(lon / NAKSHATRA_WIDTH);
  const fraction = (lon - index * NAKSHATRA_WIDTH) / NAKSHATRA_WIDTH;
  return {
    index, name: NAKSHATRAS[index],
    pada: (Math.floor(fraction * 4) + 1) as 1 | 2 | 3 | 4,
    lord: DASHA_LORDS[index % 9], fraction,
  };
}

/** Parashari: D12 starts from its own sign, then advances by 2°30' units. */
export function d12Sign(longitude: number): ZodiacSign {
  if (!finite(longitude)) throw new Error('Invalid D12 longitude');
  return mod(signOf(longitude) + Math.floor(mod(longitude, 30) / 2.5), 12) as ZodiacSign;
}

/** Explicit cyclic D6 convention: odd zodiac signs from Aries, even from Libra. */
export function d6Sign(longitude: number): ZodiacSign {
  if (!finite(longitude)) throw new Error('Invalid D6 longitude');
  const sign = signOf(longitude);
  const first = (sign % 2 === 0) ? 0 : 6;
  return mod(first + Math.floor(mod(longitude, 30) / 5), 12) as ZodiacSign;
}

/** Unrectified classical SAV. Houses are 1-indexed from the Lagna sign. */
export function calculateSav(positions: Record<Contributor, ZodiacSign>): Sarvashtakavarga {
  const bavByPlanet = {} as Record<ClassicalGraha, number[]>;
  const bySign = Array<number>(12).fill(0);
  for (const planet of CLASSICAL_GRAHAS) {
    const row = Array<number>(12).fill(0);
    for (const giver of [...CLASSICAL_GRAHAS, 'Lagna'] as Contributor[]) {
      const origin = positions[giver];
      if (!Number.isInteger(origin) || origin < 0 || origin > 11) {
        throw new Error(`SAV: invalid sign for ${giver}`);
      }
      for (const bhava of BAV[planet][giver]) {
        row[(origin + bhava - 1) % 12] += 1;
      }
    }
    if (row.reduce((a, b) => a + b, 0) !== BAV_TOTALS[planet]) {
      throw new Error(`SAV: bad classical contribution table for ${planet}`);
    }
    bavByPlanet[planet] = row;
    row.forEach((value, i) => { bySign[i] += value; });
  }
  if (bySign.reduce((a, b) => a + b, 0) !== 337) {
    throw new Error('SAV checksum mismatch; expected 337 bindus');
  }
  return {
    bySign,
    byHouse: Array.from({ length: 12 }, (_, i) => bySign[(positions.Lagna + i) % 12]),
    bavByPlanet, checksum: 337,
  };
}

function checkedShadbala(raw: VerifiedShadbalaInput): ShadbalaResult {
  if (raw?.convention !== 'parashari-sun5' || !raw.provenance?.trim()) {
    throw new Error('Shadbala: missing verified convention/provenance');
  }
  const planets = {} as ShadbalaResult['planets'];
  for (const planet of CLASSICAL_GRAHAS) {
    const data = raw.planets?.[planet];
    if (!data) throw new Error(`Shadbala: missing ${planet}`);
    const values = Object.values(data.componentsVirupas ?? {});
    if (values.length !== 6 || values.some((value) => !finite(value))) {
      throw new Error(`Shadbala: incomplete six-bala components for ${planet}`);
    }
    if (!finite(data.ishtaPhala) || !finite(data.kashtaPhala)) {
      throw new Error(`Shadbala: incomplete Ishta/Kashta for ${planet}`);
    }
    const virupas = values.reduce((a, b) => a + b, 0);
    const rupas = virupas / 60;
    const minimumRupas = SHADBALA_MINIMUM[planet];
    planets[planet] = {
      componentsVirupas: data.componentsVirupas,
      virupas, rupas, minimumRupas,
      percentage: (rupas / minimumRupas) * 100,
      ishtaPhala: data.ishtaPhala,
      kashtaPhala: data.kashtaPhala,
      netPhala: data.ishtaPhala - data.kashtaPhala,
    };
  }
  return { convention: 'parashari-sun5', provenance: raw.provenance, planets };
}

type Sample = { at: number; instant: EphemerisInstant };
function strictIsoMilliseconds(value: string): number {
  if (!/^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(?:\.\d{1,3})?(?:Z|[+-]\d\d:\d\d)$/.test(value)) {
    throw new Error('birthUtc must be ISO datetime with explicit UTC offset');
  }
  const millis = Date.parse(value);
  if (!finite(millis)) throw new Error('Invalid birthUtc');
  return millis;
}
function birthSamples(input: BirthInput): number[] {
  if (input.precision === 'unknown') {
    if (input.birthUtc !== undefined) {
      throw new Error('Unknown birth time cannot include birthUtc; provide local date and offset');
    }
    if (!/^\d{4}-\d\d-\d\d$/.test(input.birthLocalDate ?? '') ||
        !input.unknownLocalDayUtc) {
      throw new Error('Unknown time needs birthLocalDate and exact local-day UTC bounds');
    }
    const { startUtc, endUtc } = input.unknownLocalDayUtc;
    const start = strictIsoMilliseconds(startUtc);
    const end = strictIsoMilliseconds(endUtc);
    const duration = end - start;
    if (duration < 22 * 3_600_000 || duration > 26 * 3_600_000) {
      throw new Error('Invalid local civil day: expected approximately 23-25 hours');
    }
    return [0, 0.25, 0.5, 0.75, 1].map((f) => start + f * (duration - 1));
  }
  if (!input.birthUtc) throw new Error('Birth time with explicit UTC offset required');
  const center = strictIsoMilliseconds(input.birthUtc);
  const halfWidthSec: Record<Exclude<TimePrecision, 'unknown'>, number> = {
    second: 0.5, minute: 30, five_minutes: 150,
    fifteen_minutes: 450, two_hours: 3600,
  };
  const width = halfWidthSec[input.precision] * 1000;
  const factors = (input.precision === 'fifteen_minutes' || input.precision === 'two_hours')
    ? [-1, -0.5, 0, 0.5, 1]
    : [-1, 0, 1];
  return factors.map((f) => center + f * width);
}
function validateInstant(inst: EphemerisInstant) {
  if (!inst || !finite(inst.ascendantLongitude) ||
      !finite(inst.ayanamsaDegrees) || !finite(inst.julianDayUt) ||
      !inst.provenance?.trim()) throw new Error('Incomplete sidereal ephemeris result');
  for (const body of GRAHAS) {
    if (!finite(inst.bodies?.[body]?.longitude)) {
      throw new Error(`Missing ephemeris longitude: ${body}`);
    }
  }
}
function sameAcross<T>(values: T[]): T | null {
  return values.length > 0 && values.every((v) => v === values[0]) ? values[0] : null;
}
function pointAt(
  samples: Sample[],
  getter: (s: Sample) => number,
  speedGetter: ((s: Sample) => number | undefined) | null,
  lagnaSign: ZodiacSign | null,
  withHouses: boolean,
  exposeNakshatra: boolean,
  estimated: boolean,
): ChartPoint {
  const longs = samples.map(getter);
  const center = samples[Math.floor(samples.length / 2)];
  const longitude = normal(getter(center));
  const sign = sameAcross(longs.map(signOf));
  const lunarSegments = longs.map((lon) => nakshatraOf(lon));
  // Nakshatra and pada are withheld unless both are stable across samples.
  const nakshatraKey = sameAcross(lunarSegments.map((n) => `${n.index}:${n.pada}`));
  const nakshatra = exposeNakshatra && nakshatraKey ? nakshatraOf(longitude) : null;
  const speeds = speedGetter ? samples.map(speedGetter) : [];
  const speedSigns = speeds.map((value) => finite(value) ? Math.sign(value) : null);
  const speedSign = speeds.length && !speedSigns.includes(null) ? sameAcross(speedSigns) : null;
  return {
    sign,
    longitude: sign !== null ? longitude : null,
    degreeInSign: sign !== null ? mod(longitude, 30) : null,
    nakshatra,
    house: withHouses && sign !== null && lagnaSign !== null ? houseOf(sign, lagnaSign) : null,
    retrograde: speedSign === null ? null : speedSign < 0,
    estimated,
  };
}
function vargaFrom(samples: Sample[], divisor: (lon: number) => ZodiacSign): VargaChart | null {
  const ascendant = sameAcross(samples.map((s) => divisor(s.instant.ascendantLongitude)));
  if (ascendant === null) return null;
  const planets = {} as VargaChart['planets'];
  for (const planet of GRAHAS) {
    const sig = sameAcross(samples.map((s) => divisor(s.instant.bodies[planet].longitude)));
    if (sig === null) return null; // No partial fabricated divisional chart
    planets[planet] = sig;
  }
  return { lagna: ascendant, planets, houseSystem: 'whole-sign' };
}
function baseDashas(birthMs: number, moonLongitude: number) {
  const nak = nakshatraOf(moonLongitude);
  const lordIndex = DASHA_LORDS.indexOf(nak.lord);
  const elapsed = DASHA_YEARS[nak.lord] * nak.fraction * YEAR_MS;
  const start = birthMs - elapsed;
  type P = { lord: DashaLord; start: number; end: number; children?: P[] };
  function childrenOf(parent: P, level: number): P[] | undefined {
    if (level > 2) return undefined;
    const beginAt = DASHA_LORDS.indexOf(parent.lord);
    let cursor = parent.start;
    return Array.from({ length: 9 }, (_, i): P => {
      const lord = DASHA_LORDS[(beginAt + i) % 9];
      const end = i === 8
        ? parent.end // prevent floating-point drift
        : cursor + ((parent.end - parent.start) * DASHA_YEARS[lord]) / 120;
      const child: P = { lord, start: cursor, end };
      child.children = childrenOf(child, level + 1);
      cursor = end;
      return child;
    });
  }
  let cursor = start;
  const periods = Array.from({ length: 10 }, (_, i): P => {
    const lord = DASHA_LORDS[(lordIndex + i) % 9];
    const end = cursor + DASHA_YEARS[lord] * YEAR_MS;
    const root: P = { lord, start: cursor, end };
    root.children = childrenOf(root, 1);
    cursor = end;
    return root;
  });
  return { periods, natalLord: nak.lord, remainingYears: DASHA_YEARS[nak.lord] * (1 - nak.fraction) };
}
function dashaTimeline(samples: Sample[]): VimshottariTimeline | null {
  const nakshatras = samples.map((s) => nakshatraOf(s.instant.bodies.Moon.longitude).index);
  if (sameAcross(nakshatras) === null) return null;
  const all = samples.map((s) => baseDashas(s.at, s.instant.bodies.Moon.longitude));
  const center = Math.floor(samples.length / 2);
  const natal = all[center];
  type RawPeriod = (typeof natal.periods)[number];
  function merge(path: number[], level: DashaPeriod['level']): DashaPeriod {
    function locate(i: number): RawPeriod {
      let p = all[i].periods[path[0]];
      for (const index of path.slice(1)) p = p.children![index];
      return p;
    }
    const variants = all.map((_, i) => locate(i));
    const core = variants[center];
    const minStart = Math.min(...variants.map((p) => p.start));
    const maxStart = Math.max(...variants.map((p) => p.start));
    const minEnd = Math.min(...variants.map((p) => p.end));
    const maxEnd = Math.max(...variants.map((p) => p.end));
    const monthStable = month(minStart) === month(maxStart) && month(minEnd) === month(maxEnd);
    const result: DashaPeriod = {
      lord: core.lord, level,
      startsAtUtc: iso(core.start), endsAtUtc: iso(core.end),
      startRangeUtc: [iso(minStart), iso(maxStart)],
      endRangeUtc: [iso(minEnd), iso(maxEnd)],
      startMonth: month(minStart) === month(maxStart) ? month(minStart) : null,
      endMonth: month(minEnd) === month(maxEnd) ? month(minEnd) : null,
      monthStable,
      startsAtAgeYears: (core.start - samples[center].at) / YEAR_MS,
      endsAtAgeYears: (core.end - samples[center].at) / YEAR_MS,
    };
    if (level !== 'pratyantar') {
      result.children = Array.from({ length: 9 }, (_, j) =>
        merge([...path, j], level === 'maha' ? 'antar' : 'pratyantar'));
    }
    return result;
  }
  return {
    nakshatraLord: natal.natalLord,
    birthMahadashaRemainingYears: natal.remainingYears,
    yearConvention: '365.25_days',
    periods: Array.from({ length: 10 }, (_, i) => merge([i], 'maha')),
  };
}

export async function calculateJyotishChart(
  input: BirthInput,
  ephemeris: JyotishEphemeris,
): Promise<JyotishChartResult> {
  if (!finite(input.latitude) || Math.abs(input.latitude) > 90 ||
      !finite(input.longitude) || Math.abs(input.longitude) > 180) {
    throw new Error('Invalid birth coordinates');
  }
  if (!(input.precision in TIME_PRECISION_RULES)) throw new Error('Invalid time precision');
  const ayanamsa = input.ayanamsa ?? 'lahiri';
  if (!(['lahiri', 'raman', 'kp'] as string[]).includes(ayanamsa)) {
    throw new Error('Unsupported ayanamsa');
  }
  const instants = birthSamples(input);
  const samples: Sample[] = [];
  // Sequential intentionally: some Swiss Ephemeris bindings use global mode state.
  for (const at of instants) {
    const instant = await ephemeris.calculateInstant({
      utc: iso(at), latitude: input.latitude,
      longitude: input.longitude, ayanamsa,
    });
    validateInstant(instant);
    samples.push({ at, instant });
  }
  const provenance = sameAcross(samples.map((s) => s.instant.provenance));
  if (provenance === null) throw new Error('Inconsistent ephemeris provenance');
  const lowPrecision = input.precision === 'unknown' || input.precision === 'two_hours';
  const estimated = input.precision !== 'second';
  const lagnaSign = lowPrecision ? null :
    sameAcross(samples.map((s) => signOf(s.instant.ascendantLongitude)));
  const planetsBySign = {} as Record<Graha, ZodiacSign | null>;
  for (const graha of GRAHAS) {
    planetsBySign[graha] = sameAcross(samples.map((s) => signOf(s.instant.bodies[graha].longitude)));
  }
  let d1: Chart | null = null;
  if (!lowPrecision) {
    const asc = pointAt(samples, (s) => s.instant.ascendantLongitude,
      null, lagnaSign, true, true, estimated);
    const planets = {} as Chart['planets'];
    for (const graha of GRAHAS) {
      planets[graha] = pointAt(samples,
        (s) => s.instant.bodies[graha].longitude,
        (s) => s.instant.bodies[graha].speedLongitude,
        lagnaSign, true, true, estimated);
    }
    d1 = { lagna: asc, planets, houseSystem: 'whole-sign' };
  }
  const completeHouseChart = lagnaSign !== null && GRAHAS.every((p) => planetsBySign[p] !== null);
  const d12 = !lowPrecision && completeHouseChart ? vargaFrom(samples, d12Sign) : null;
  const d6 = !lowPrecision && completeHouseChart ? vargaFrom(samples, d6Sign) : null;
  let sav: Sarvashtakavarga | null = null;
  if (!lowPrecision && completeHouseChart) {
    const positions = { Lagna: lagnaSign } as Record<Contributor, ZodiacSign>;
    for (const graha of CLASSICAL_GRAHAS) {
      positions[graha] = planetsBySign[graha]!;
    }
    sav = calculateSav(positions);
  }
  const dasha = lowPrecision ? null : dashaTimeline(samples);
  let shadbala: ShadbalaResult | null = null;
  if ((input.precision === 'second' || input.precision === 'minute') &&
      completeHouseChart && ephemeris.calculateShadbala) {
    const central = samples[Math.floor(samples.length / 2)];
    const raw = await ephemeris.calculateShadbala({
      utc: iso(central.at), latitude: input.latitude,
      longitude: input.longitude, ayanamsa,
    });
    shadbala = checkedShadbala(raw);
  }
  let twelfthLord: TwelfthLordPlacement | null = null;
  if (lagnaSign !== null) {
    const ownsSign = mod(lagnaSign + 11, 12) as ZodiacSign;
    const lord = SIGN_LORDS[ownsSign];
    const placedInSign = planetsBySign[lord];
    if (placedInSign !== null) {
      const placedInHouse = houseOf(placedInSign, lagnaSign);
      const houseTypes: TwelfthLordPlacement['houseTypes'] = [];
      if ([1,4,7,10].includes(placedInHouse)) houseTypes.push('kendra');
      if ([1,5,9].includes(placedInHouse)) houseTypes.push('trikona');
      if ([6,8,12].includes(placedInHouse)) houseTypes.push('dusthana');
      if ([3,6,10,11].includes(placedInHouse)) houseTypes.push('upachaya');
      twelfthLord = { lord, ownsSign, placedInSign, placedInHouse, houseTypes };
    }
  }
  const reason = (available: boolean, denied: string): ModuleStatus => ({
    available, reason: available ? null : denied,
  });
  const precisionWarning = '時間誤差取樣下不穩定；已停止輸出該分盤或宮位。';
  const status: JyotishChartResult['moduleStatus'] = {
    D1: reason(!!d1 && lagnaSign !== null,
      lowPrecision ? '出生時辰不足；不上升與宮位。' : precisionWarning),
    D12: reason(d12 !== null,
      lowPrecision ? '出生時辰不足；不計算 D-12。' : precisionWarning),
    D6: reason(d6 !== null,
      lowPrecision ? '出生時辰不足；不計算 D-6。' : precisionWarning),
    SAV: reason(sav !== null,
      lowPrecision ? 'SAV 包含 Lagna 貢獻；時辰不足時不可完整計算。' : precisionWarning),
    Dasha: reason(dasha !== null,
      lowPrecision ? '出生時間不足；不發布 Vimshottari 時間線。'
        : '月亮宿在出生時間誤差內改變；Dasha 不作判定。'),
    Shadbala: reason(shadbala !== null,
      lowPrecision ? '時辰精度不足。' :
        '尚未接入完整六種 Bala 與 Ishta/Kashta 的已驗證計算器，禁止填值。'),
    D60: reason(false, '此引擎未實作 D-60；有秒級時間亦不得宣稱已算。分鐘精度另需 ±2 分鐘穩定檢查。'),
  };
  return {
    input, ayanamsa, provenance,
    reliability: TIME_PRECISION_RULES[input.precision].reliability,
    timeNotice: TIME_PRECISION_RULES[input.precision].detail,
    moduleStatus: status,
    planetsBySign, d1, d12, d6, sav, dasha, shadbala, twelfthLord,
  };
}
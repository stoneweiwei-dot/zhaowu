若要保留，它们只能暂时归入「实验性玄学参数」：可以作为未来模型测试的假设值，但不能在网站中冒充已验证地球物理数据。这一点必须明确，否则一个没有来源的精确小数，就足以让整个思想体系的可信度一起崩掉。

真正值得保留的思路，是空间分析不应只看罗盘刻度，而可以区分真北、磁北、纬度、太阳路径、季节、地形与建筑环境。至于科里奥利力，它主要影响大尺度流体与气象系统，不能直接证明「北半球青龙木旺、南半球白虎金旺」。青龙白虎可以是传统空间象征，科里奥利则是物理机制，两者可以并列研究，不能互相伪装成证据。


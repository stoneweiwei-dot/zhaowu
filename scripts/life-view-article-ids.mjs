#!/usr/bin/env node
// Keeps the Supabase allowlist public.life_view_article_ids in sync with ARTICLE_CATALOG.
// Run with the tsx loader (the catalog is TypeScript):
//   node --import tsx scripts/life-view-article-ids.mjs --check   # exit 1 if catalog and seeds differ
//   node --import tsx scripts/life-view-article-ids.mjs --sql     # print a seed block for ids missing from migrations
// A new article therefore needs a new migration containing the printed block (applied with the release).
import { readdirSync, readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const MIGRATIONS = join(ROOT, "supabase", "migrations");
export const SEED_BEGIN = "-- BEGIN life_view_article_ids seed";
export const SEED_END = "-- END life_view_article_ids seed";
const ID_RE = /^[a-z0-9][a-z0-9-]{0,119}$/;

export async function catalogIds() {
  const mod = await import(pathToFileURL(join(ROOT, "src", "components", "life-view-home-section.tsx")).href);
  return [...new Set(mod.ARTICLE_CATALOG.map((a) => a.id))].sort();
}

export function seededIds() {
  const ids = new Set();
  for (const f of readdirSync(MIGRATIONS).filter((n) => n.endsWith(".sql")).sort()) {
    const sql = readFileSync(join(MIGRATIONS, f), "utf8");
    let at = 0;
    for (;;) {
      const b = sql.indexOf(SEED_BEGIN, at);
      if (b < 0) break;
      const e = sql.indexOf(SEED_END, b);
      if (e < 0) throw new Error(`${f}: unterminated seed block`);
      for (const m of sql.slice(b, e).matchAll(/\('([^']+)'\)/g)) ids.add(m[1]);
      at = e + SEED_END.length;
    }
  }
  return [...ids].sort();
}

export function seedBlock(ids) {
  return [
    `${SEED_BEGIN} (generated by scripts/life-view-article-ids.mjs --sql; do not edit by hand)`,
    "insert into public.life_view_article_ids (article_id) values",
    ids.map((id) => `  ('${id}')`).join(",\n"),
    "on conflict (article_id) do nothing;",
    SEED_END,
  ].join("\n");
}

export async function diff() {
  const cat = await catalogIds();
  const seed = new Set(seededIds());
  const catSet = new Set(cat);
  return {
    invalid: cat.filter((id) => !ID_RE.test(id)),
    missing: cat.filter((id) => !seed.has(id)),
    extra: [...seed].filter((id) => !catSet.has(id)),
  };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const d = await diff();
  if (process.argv.includes("--sql")) {
    console.log(d.missing.length ? seedBlock(d.missing) : "-- nothing to seed: allowlist already covers ARTICLE_CATALOG");
  } else {
    const bad = d.invalid.length + d.missing.length + d.extra.length;
    if (d.invalid.length) console.error("ids not matching ^[a-z0-9][a-z0-9-]{0,119}$:", d.invalid.join(", "));
    if (d.missing.length) console.error("in ARTICLE_CATALOG but not seeded (run --sql, add a migration):", d.missing.join(", "));
    if (d.extra.length) console.error("seeded but not in ARTICLE_CATALOG:", d.extra.join(", "));
    if (bad) process.exit(1);
    console.log("life_view_article_ids seed matches ARTICLE_CATALOG");
  }
}
